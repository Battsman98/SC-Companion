"""Run after adding home photos: python scripts/prepare_home_images.py."""
import hashlib
import json
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
HOME = ROOT / "web/media/home"


def main():
    optimized = HOME / "optimized"
    optimized.mkdir(exist_ok=True)
    photos = []
    for path in sorted(HOME.iterdir(), key=lambda p: p.name):
        if path.suffix.lower() not in {".jpg", ".jpeg", ".png", ".webp"}:
            continue
        if path.name == "made-by-community.png":
            continue
        if path.name.startswith("sc-") and path.stem.endswith(("-mobile", "-tablet")):
            continue
        if path.name.startswith("sc-") and path.stem.endswith("-wide"):
            photos.append({size: path.name.replace("-wide", f"-{size}") for size in ("mobile", "tablet", "wide")})
        elif path.suffix.lower() == ".webp":
            photos.append({"wide": path.name})
        else:
            digest = hashlib.sha256(path.read_bytes()).hexdigest()[:16]
            target = optimized / f"{digest}.webp"
            if not target.exists():
                with Image.open(path) as source:
                    image = ImageOps.exif_transpose(source).convert("RGB")
                    image.thumbnail((2560, 1440), Image.Resampling.LANCZOS)
                    image.save(target, "WEBP", quality=82, method=6)
            photos.append({"wide": f"optimized/{target.name}"})
    (ROOT / "web/home-images.js").write_text(
        "// Generated by scripts/prepare_home_images.py\nwindow.homeImagePool = "
        + json.dumps(photos, indent=2) + ";\n", encoding="utf-8"
    )
    print(f"Prepared {len(photos)} distinct photos; originals preserved.")


if __name__ == "__main__":
    main()
